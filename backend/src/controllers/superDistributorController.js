// DELETE /api/super-distributors/me/schools/:id
async function deleteMySchool(req, res) {
  try {
    const mine = await isMySchool(req.user.id, req.params.id);
    if (!mine) return res.status(403).json({ error: 'Access denied' });

    const [rows] = await pool.query('SELECT * FROM schools WHERE id = ?', [req.params.id]);
    if (rows.length === 0) return res.status(404).json({ error: 'School not found' });
    if (rows[0].status !== 'pending') {
      return res.status(409).json({ error: 'Only pending schools can be withdrawn. Contact Super Admin.' });
    }

    const adminUserId = rows[0].admin_user_id;
    await pool.query('DELETE FROM schools WHERE id = ?', [req.params.id]);
    if (adminUserId) await pool.query("DELETE FROM users WHERE id = ? AND role = 'schoolAdmin'", [adminUserId]);

    res.json({ message: 'School withdrawn successfully' });
  } catch (err) {
    console.error('SD deleteMySchool error:', err.message);
    res.status(500).json({ error: 'Server error deleting school' });
  }
}

