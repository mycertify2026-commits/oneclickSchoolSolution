async function changeMyPassword(req, res) {
  try {
    const { currentPassword, newPassword } = req.body;
    if (!currentPassword || !newPassword) return res.status(400).json({ error: 'Current and new password are required' });
    if (newPassword.length < 8) return res.status(400).json({ error: 'New password must be at least 8 characters' });

    const [rows] = await pool.query('SELECT password_hash FROM users WHERE id = ?', [req.user.id]);
    const valid = await bcrypt.compare(currentPassword, rows[0]?.password_hash || '');
    if (!valid) return res.status(401).json({ error: 'Current password is incorrect' });

    const hash = await bcrypt.hash(newPassword, 10);
    await pool.query('UPDATE users SET password_hash = ?, password_set = 1 WHERE id = ?', [hash, req.user.id]);
    await logAudit({ userId: req.user.id, action: 'PASSWORD_CHANGED', ipAddress: req.ip });
    res.json({ message: 'Password changed successfully' });
  } catch (err) {
    console.error('SD changeMyPassword error:', err.message);
    res.status(500).json({ error: 'Server error changing password' });
  }
}

// GET /api/super-distributors/me/dashboard
async function getDashboard(req, res) {
  try {
    const sdId = req.user.id;

    // Total distributors under this SD
    const [distCount] = await pool.query(
      'SELECT COUNT(*) as c FROM distributors WHERE super_distributor_id = ? AND deleted_at IS NULL',
      [sdId]
    );

    // Total schools (direct + via distributors)
    const [schoolCount] = await pool.query(
      `SELECT COUNT(*) as c FROM schools s
       LEFT JOIN distributors d ON d.id = s.distributor_id
       WHERE s.deleted_at IS NULL
         AND (s.super_distributor_id = ? OR d.super_distributor_id = ?)`,
      [sdId, sdId]
    );

    // Pending schools
    const [pendingCount] = await pool.query(
      `SELECT COUNT(*) as c FROM schools s
       LEFT JOIN distributors d ON d.id = s.distributor_id
       WHERE s.deleted_at IS NULL AND s.status = 'pending'
         AND (s.super_distributor_id = ? OR d.super_distributor_id = ?)`,
      [sdId, sdId]
    );

    // Revenue: sum of certificate prices from schools under this SD
    const [revenueRows] = await pool.query(
      `SELECT COALESCE(SUM(c.price), 0) as total
       FROM certificates c
       JOIN schools s ON s.id = c.school_id
       LEFT JOIN distributors d ON d.id = s.distributor_id
       WHERE s.deleted_at IS NULL
         AND (s.super_distributor_id = ? OR d.super_distributor_id = ?)`,
      [sdId, sdId]
    );

    // Recently added schools
    const [recentSchools] = await pool.query(
      `SELECT s.id, s.name, s.status, s.created_at,
              u_admin.name as admin_name,
              du.name as distributor_name, du.mobile as distributor_phone
       FROM schools s
       LEFT JOIN users u_admin ON u_admin.id = s.admin_user_id
       LEFT JOIN distributors d ON d.id = s.distributor_id
       LEFT JOIN users du ON du.id = d.user_id
       WHERE s.deleted_at IS NULL
         AND (s.super_distributor_id = ? OR d.super_distributor_id = ?)
       ORDER BY s.created_at DESC LIMIT 10`,
      [sdId, sdId]
    );

    // Actual earnings — from the commission ledger's permanent snapshot,
    // never recalculated from today's percentages. commission_ledger stores
    // super_distributor_id directly, so no school/distributor join is needed.
    const [[earnings]] = await pool.query(
      `SELECT COALESCE(SUM(super_distributor_amount),0) as total,
              COALESCE(SUM(CASE WHEN DATE(created_at)=CURDATE() THEN super_distributor_amount ELSE 0 END),0) as today,
              COALESCE(SUM(CASE WHEN YEAR(created_at)=YEAR(CURDATE()) AND MONTH(created_at)=MONTH(CURDATE()) THEN super_distributor_amount ELSE 0 END),0) as this_month,
              COUNT(*) as total_certificates
       FROM commission_ledger WHERE super_distributor_id = ? AND status='confirmed'`,
      [sdId]
    );
    const [byType] = await pool.query(
      `SELECT certificate_type, COALESCE(SUM(super_distributor_amount),0) as total, COUNT(*) as count
       FROM commission_ledger WHERE super_distributor_id = ? AND status='confirmed' GROUP BY certificate_type`,
      [sdId]
    );
    const [byDistributor] = await pool.query(
      `SELECT d.id as distributor_id, u.name as distributor_name, COALESCE(SUM(cl.super_distributor_amount),0) as total
       FROM commission_ledger cl
       JOIN distributors d ON d.id = cl.distributor_id
       JOIN users u ON u.id = d.user_id
       WHERE cl.super_distributor_id = ? AND cl.status='confirmed'
       GROUP BY d.id, u.name ORDER BY total DESC`,
      [sdId]
    );

    // Flat SD commission — this SD's own commission_rate (%) applied to the
    // price of every certificate generated under this SD's hierarchy.
    // Separate from, and additional to, the commission_ledger split above.
    const [[sdProfile]] = await pool.query(
      `SELECT commission_rate FROM distributors WHERE user_id = ? AND super_distributor_id IS NULL AND deleted_at IS NULL LIMIT 1`,
      [sdId]
    );
    const flatRate = sdProfile ? Number(sdProfile.commission_rate) || 0 : 0;
    const [flatByMonth] = await pool.query(
      `SELECT DATE_FORMAT(c.created_at, '%Y-%m') as month, COALESCE(SUM(c.price),0) as certTotal, COUNT(*) as count
       FROM certificates c
       JOIN schools s ON s.id = c.school_id
       LEFT JOIN distributors d ON d.id = s.distributor_id
       WHERE s.deleted_at IS NULL
         AND (s.super_distributor_id = ? OR d.super_distributor_id = ?)
         AND c.created_at >= DATE_SUB(CURDATE(), INTERVAL 6 MONTH)
       GROUP BY month ORDER BY month ASC`,
      [sdId, sdId]
    );
    const flatCommission = {
      rate: flatRate,
      total: Number((Number(revenueRows[0].total) * flatRate / 100).toFixed(2)),
      byMonth: flatByMonth.map(r => ({
        month: r.month,
        certificateTotal: Number(r.certTotal),
        commission: Number((Number(r.certTotal) * flatRate / 100).toFixed(2)),
        count: Number(r.count),
      })),
    };

    res.json({
      totalDistributors: Number(distCount[0].c),
      totalSchools: Number(schoolCount[0].c),
      pendingSchools: Number(pendingCount[0].c),
      revenue: Number(revenueRows[0].total),
      recentSchools,
      earnings: {
        total: Number(earnings.total),
        today: Number(earnings.today),
        thisMonth: Number(earnings.this_month),
        totalCertificates: Number(earnings.total_certificates),
        byCertificateType: byType.map(r => ({ type: r.certificate_type, total: Number(r.total), count: Number(r.count) })),
        byDistributor: byDistributor.map(r => ({ distributorId: r.distributor_id, name: r.distributor_name, total: Number(r.total) })),
      },
      flatCommission,
    });
  } catch (err) {
    console.error('SD getDashboard error:', err.message);
    res.status(500).json({ error: 'Server error fetching dashboard' });
  }
}

