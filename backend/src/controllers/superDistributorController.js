async function createSuperDistributor(req, res) {
  const conn = await pool.getConnection();
  try {
    const { name, email, mobile, city, district, address, area_of_operation, commission_rate, password, confirmPassword,
            pan_number, bank_account_holder, bank_name, bank_account_number, bank_ifsc } = req.body;
    if (!name || !email) return res.status(400).json({ error: 'Name and email are required' });
    if (!district) return res.status(400).json({ error: 'District is required' });

    if (password !== undefined && password !== '') {
      if (password.length < 8) return res.status(400).json({ error: 'Password must be at least 8 characters' });
      if (confirmPassword !== undefined && password !== confirmPassword) {
        return res.status(400).json({ error: 'Password and confirm password do not match' });
      }
    }

    const [existing] = await conn.query('SELECT id FROM users WHERE email = ? AND deleted_at IS NULL', [email.toLowerCase().trim()]);
    if (existing.length > 0) return res.status(409).json({ error: 'A user with this email already exists' });

    await conn.beginTransaction();

    const userId = uuidv4();
    const hasPassword = Boolean(password);
    const passwordHash = hasPassword ? await bcrypt.hash(password, 10) : null;

    await conn.query(
      `INSERT INTO users (id, role, name, email, mobile, password_hash, is_active, password_set, created_by) VALUES (?, 'superDistributor', ?, ?, ?, ?, 1, ?, ?)`,
      [userId, name, email.toLowerCase().trim(), mobile || null, passwordHash, hasPassword ? 1 : 0, req.user.id]
    );

    // Store SD profile in distributors table (reusing same table, with super_distributor_id = NULL).
    // commission_rate here is the SD's own flat commission — a % of the price
    // of every certificate generated by schools under this SD's hierarchy —
    // separate from (and in addition to) the School/Platform split engine.
    // Defaults to 2%, matching the business rule; Super Admin can override.
    const sdId = uuidv4();
    await conn.query(
      `INSERT INTO distributors (id, user_id, commission_rate, city, district, address, area_of_operation,
                                  pan_number, bank_account_holder, bank_name, bank_account_number, bank_ifsc)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      [sdId, userId, commission_rate !== undefined && commission_rate !== '' ? commission_rate : 2.0, city || null, district, address || null, area_of_operation || null,
       pan_number || null, bank_account_holder || null, bank_name || null, bank_account_number || null, bank_ifsc || null]
    );

    await conn.commit();

    let message;
    if (hasPassword) {
      message = 'Super Distributor created. They can log in immediately.';
      sendSuperDistributorCreatedEmail(email, name, {
        username: email.toLowerCase().trim(),
        password,
        loginUrl: req.headers.origin,
        relatedUserId: userId,
      }).catch(e => console.error('SD welcome email failed:', e.message));
    } else {
      const emailResult = await createAndSendPasswordToken(
        { id: userId, name, email, role: 'superDistributor' },
        'setup',
        req.headers.origin,
        { role: 'superDistributor', username: email.toLowerCase().trim() }
      );
      if (!emailResult.success) console.error('SD setup email failed:', emailResult.error);
      message = 'Super Distributor created. Password setup email sent.';
    }

    const [rows] = await pool.query(
       `SELECT u.id, u.name, u.email, u.mobile, u.is_active, d.district, d.city, d.address, d.area_of_operation,
               d.commission_rate, d.avatar_url, d.pan_number, d.bank_account_holder, d.bank_name, d.bank_account_number, d.bank_ifsc
       FROM users u LEFT JOIN distributors d ON d.user_id = u.id WHERE u.id = ?`,
      [userId]
    );
    res.status(201).json({ superDistributor: rows[0], message });
  } catch (err) {
    await conn.rollback();
    console.error('createSuperDistributor error:', err.message);
    res.status(500).json({ error: 'Server error creating super distributor' });
  } finally {
    conn.release();
  }
}

